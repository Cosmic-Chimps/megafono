#!/usr/bin/env bash
# Starts the local development fediverse (see README.md) and creates a user on GoToSocial (and Mastodon).
# Safe to run again: it keeps .env, re-ups the stack, skips users that exist and mints a fresh GoToSocial token.
#
#   ./setup.sh [--mastodon] [--published] [--user NAME]
#
# Needs docker (with compose), curl and openssl. Works with bash 3.2 (macOS) and Linux.
set -euo pipefail

cd "$(dirname "$0")"

with_mastodon=0
published=0
user=bob

while [ $# -gt 0 ]; do
  case "$1" in
    --mastodon) with_mastodon=1 ;;
    --published) published=1 ;;
    --user)
      [ $# -ge 2 ] || { echo "--user needs a name" >&2; exit 2; }
      user="$2"
      shift
      ;;
    -h|--help)
      sed -n '2,7p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) echo "unknown option: $1 (try --help)" >&2; exit 2 ;;
  esac
  shift
done

case "$user" in
  *[!a-z0-9_]*|"") echo "--user must be lowercase letters, digits and underscores" >&2; exit 2 ;;
esac

for tool in docker curl openssl; do
  command -v "$tool" >/dev/null 2>&1 || { echo "$tool is required but not installed" >&2; exit 1; }
done

dc=(docker compose -f compose.yaml)
[ "$published" -eq 1 ] && dc+=(-f compose.published.yaml)
[ "$with_mastodon" -eq 1 ] && dc+=(--profile mastodon)

log() { printf '\n== %s\n' "$*"; }

# ---- 1. .env ------------------------------------------------------------------------------------------------------

if [ -f .env ]; then
  echo ".env exists: keeping it (the master key must match the database volume)"
elif docker volume inspect megafono-dev_db-data >/dev/null 2>&1; then
  # The volumes belong to the project name, not to this folder: another checkout (or a deleted .env) left them behind,
  # and a new master key could not decrypt the actors' keys stored there
  echo "No .env here, but the volume megafono-dev_db-data exists (from another checkout, or .env was deleted)." >&2
  echo "Copy that checkout's deploy/dev-fediverse/.env here, or start from zero (removes every container and volume of it):" >&2
  echo "  docker rm -f \$(docker ps -aq --filter label=com.docker.compose.project=megafono-dev)" >&2
  echo "  docker volume rm \$(docker volume ls -q --filter label=com.docker.compose.project=megafono-dev)" >&2
  exit 1
else
  log "Generating .env"
  cat > .env <<EOF
# Generated by setup.sh. Development secrets for the local fediverse: never reuse them anywhere else.
# Do not delete this file while the db-data volume exists: the master key must match what the database holds.
# docker compose down -v removes the volumes; delete this file only after that.

MEGAFONO_MASTER_KEY=$(openssl rand -base64 32)
MEGAFONO_TOKEN=$(openssl rand -hex 32)
MEGAFONO_WEBHOOK_SECRET=$(openssl rand -hex 32)
POSTGRES_PASSWORD=$(openssl rand -hex 24)
SAMPLE_ADMIN_PASSWORD=$(openssl rand -hex 16)

# Password of the GoToSocial users setup.sh creates. The suffix keeps GoToSocial's strength check happy.
GTS_PASSWORD=$(openssl rand -hex 12)-Aa1

# Mastodon (only used with --mastodon). The three encryption keys are 32 characters.
MASTODON_SECRET_KEY_BASE=$(openssl rand -hex 64)
MASTODON_AR_DETERMINISTIC_KEY=$(openssl rand -hex 16)
MASTODON_AR_KEY_DERIVATION_SALT=$(openssl rand -hex 16)
MASTODON_AR_PRIMARY_KEY=$(openssl rand -hex 16)
MASTODON_DB_PASSWORD=$(openssl rand -hex 24)

# To run your own app instead of the sample, give its address as the gateway and Megáfono must reach it, then
# docker compose up -d (README.md, "Pointing a real app at it"). An app on the host:
#APP_URL=http://host.docker.internal:5000
EOF
  chmod 600 .env
fi

set -a
# shellcheck disable=SC1091
. ./.env
set +a

# ---- 2. Start the stack -------------------------------------------------------------------------------------------

log "Starting the stack (the first build takes a few minutes)"
"${dc[@]}" up -d --build

# ---- 3. Export Caddy's root certificate ---------------------------------------------------------------------------

log "Exporting Caddy's root certificate to caddy-root.crt"
exported=0
for _ in $(seq 1 30); do
  if "${dc[@]}" cp caddy:/data/caddy/pki/authorities/local/root.crt ./caddy-root.crt.new >/dev/null 2>&1; then
    exported=1
    break
  fi
  sleep 1
done
[ "$exported" -eq 1 ] || { echo "could not copy Caddy's root certificate: docker compose logs caddy" >&2; exit 1; }

if [ -f caddy-root.crt ] && ! cmp -s caddy-root.crt caddy-root.crt.new; then
  echo "NOTE: the CA changed (the caddy-data volume was recreated). Trust the new caddy-root.crt, and remove the old one from your trust store."
fi
mv caddy-root.crt.new caddy-root.crt

# curl from the host works before /etc/hosts or any trust is set up: it resolves the names itself and trusts the exported CA only
host_curl() {
  local name="$1"
  shift
  curl -sS --resolve "$name:443:127.0.0.1" --cacert caddy-root.crt "$@"
}

# ---- 4. Wait for the services -------------------------------------------------------------------------------------

# wait_for NAME URL SERVICE SECONDS: waits for a 200 (GoToSocial answers 503 while it starts)
wait_for() {
  local name="$1" url="$2" service="$3" seconds="$4" host code="000" waited=0
  host="${url#https://}"
  host="${host%%/*}"
  printf 'Waiting for %s' "$name"
  while [ "$waited" -lt "$seconds" ]; do
    code=$(host_curl "$host" -o /dev/null -w '%{http_code}' "$url" 2>/dev/null || true)
    if [ "$code" = "200" ]; then
      echo " ok"
      return 0
    fi
    printf '.'
    sleep 3
    waited=$((waited + 3))
  done
  echo
  echo "$name did not answer 200 at $url within ${seconds} s (last status: $code). Look at: docker compose logs $service" >&2
  exit 1
}

log "Waiting for the services"
wait_for "Megáfono behind the gateway" https://app.test/.well-known/nodeinfo megafono 180
wait_for "GoToSocial" https://gts.test/api/v1/instance gotosocial 180

# ---- 5. GoToSocial user and token ---------------------------------------------------------------------------------

# Reads one string field of a flat JSON object from stdin
json_field() {
  if command -v jq >/dev/null 2>&1; then
    jq -r ".$1 // empty"
  else
    sed -n "s/.*\"$1\":\"\\([^\"]*\\)\".*/\\1/p"
  fi
}

log "GoToSocial user @$user@gts.test"
rc=0
out=$("${dc[@]}" exec -T gotosocial /gotosocial/gotosocial admin account create \
  --username "$user" --email "$user@gts.test" --password "$GTS_PASSWORD" 2>&1) || rc=$?
if [ "$rc" -eq 0 ]; then
  echo "created"
elif grep -qiE 'already|exists|in use|taken' <<<"$out"; then
  echo "exists already: keeping it"
else
  printf '%s\n' "$out" >&2
  echo "creating the GoToSocial user failed (exit $rc)" >&2
  exit 1
fi

# The same OAuth sign-in as the interop tests (GoToSocialServer.fs, ObtainToken), without a browser
log "Getting a GoToSocial access token"
jar=$(mktemp)
trap 'rm -f "$jar"' EXIT
redirect="urn:ietf:wg:oauth:2.0:oob"
gts() { host_curl gts.test -b "$jar" -c "$jar" "$@"; }

app_json=$(gts https://gts.test/api/v1/apps \
  --data-urlencode "client_name=megafono-dev" \
  --data-urlencode "redirect_uris=$redirect" \
  --data-urlencode "scopes=read write follow")
client_id=$(printf '%s' "$app_json" | json_field client_id)
client_secret=$(printf '%s' "$app_json" | json_field client_secret)
[ -n "$client_id" ] && [ -n "$client_secret" ] || { echo "registering the OAuth app failed: $app_json" >&2; exit 1; }

authorize_url="https://gts.test/oauth/authorize?client_id=$client_id&redirect_uri=urn%3Aietf%3Awg%3Aoauth%3A2.0%3Aoob&response_type=code&scope=read+write+follow"
gts -o /dev/null "$authorize_url" # 303 to /auth/sign_in, and the session cookie
gts -o /dev/null https://gts.test/auth/sign_in \
  --data-urlencode "username=$user@gts.test" --data-urlencode "password=$GTS_PASSWORD" # 302 to /oauth/authorize
gts -o /dev/null "$authorize_url" # the "Allow" page
location=$(gts -o /dev/null -D - https://gts.test/oauth/authorize --data '' | tr -d '\r' | sed -n 's/^[Ll]ocation: *//p')
code=$(printf '%s' "$location" | sed -n 's/.*[?&]code=\([^&]*\).*/\1/p')
[ -n "$code" ] || { echo "no authorization code (Location: '$location'): docker compose logs gotosocial" >&2; exit 1; }

token_json=$(gts https://gts.test/oauth/token \
  --data-urlencode "grant_type=authorization_code" \
  --data-urlencode "client_id=$client_id" \
  --data-urlencode "client_secret=$client_secret" \
  --data-urlencode "redirect_uri=$redirect" \
  --data-urlencode "code=$code")
gts_token=$(printf '%s' "$token_json" | json_field access_token)
[ -n "$gts_token" ] || { echo "no access token: $token_json" >&2; exit 1; }
umask 077
printf '%s\n' "$gts_token" > .gts-token

# ---- 6. Mastodon --------------------------------------------------------------------------------------------------

mastodon_note=""
if [ "$with_mastodon" -eq 1 ]; then
  log "Mastodon (the first start loads the schema and takes a few minutes)"
  wait_for "Mastodon" https://mastodon.test/health mastodon-web 600
  rc=0
  out=$("${dc[@]}" exec -T mastodon-web bin/tootctl accounts create "$user" \
    --email "$user@mastodon.test" --confirmed --approve 2>&1) || rc=$?
  if [ "$rc" -eq 0 ]; then
    printf '%s\n' "$out"
    mastodon_note="created @$user@mastodon.test (sign in at https://mastodon.test with $user@mastodon.test and the password above)"
  elif grep -qiE 'already|exists|taken' <<<"$out"; then
    echo "exists already: keeping it"
    mastodon_note="@$user@mastodon.test exists already. The password is shown only at creation: docker compose --profile mastodon exec mastodon-web bin/tootctl accounts modify $user --reset-password"
  else
    printf '%s\n' "$out" >&2
    echo "creating the Mastodon user failed (exit $rc)" >&2
    exit 1
  fi
fi

# ---- 7. Summary ---------------------------------------------------------------------------------------------------

cat <<EOF

== Ready

1. Make the three names resolve to this machine (once):
     echo "127.0.0.1 app.test gts.test mastodon.test" | sudo tee -a /etc/hosts

2. Trust Caddy's root certificate so the browser accepts https://*.test (once; Firefox keeps its own store):
     macOS:           sudo security add-trusted-cert -d -r trustRoot -k /Library/Keychains/System.keychain "$PWD/caddy-root.crt"
     Debian/Ubuntu:   sudo cp "$PWD/caddy-root.crt" /usr/local/share/ca-certificates/megafono-dev.crt && sudo update-ca-certificates
     Fedora/Arch:     sudo trust anchor --store "$PWD/caddy-root.crt"

3. Open:
     https://app.test/u/alice            sample app, a locked user (also: /u/test)
     https://app.test/u/alice/manage     approve follows, publish; any user name, password: $SAMPLE_ADMIN_PASSWORD
     https://gts.test                    GoToSocial (user $user, password $GTS_PASSWORD)
EOF
if [ "$with_mastodon" -eq 1 ]; then
  echo "     https://mastodon.test               Mastodon: $mastodon_note"
fi
cat <<EOF

Megáfono's internal API (development only, loopback only):
     curl -H "Authorization: Bearer $MEGAFONO_TOKEN" http://127.0.0.1:8081/health

GoToSocial access token for @$user@gts.test (also in .gts-token):
     $gts_token
     curl -H "Authorization: Bearer \$(cat .gts-token)" https://gts.test/api/v1/accounts/verify_credentials

Reset everything with: docker compose down -v   (then delete .env and caddy-root.crt, and untrust the old CA)
EOF
